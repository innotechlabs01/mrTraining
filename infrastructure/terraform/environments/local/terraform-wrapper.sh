#!/bin/bash
# Terraform wrapper script for MR Training local environment
# Sets up Floci GCP emulator environment variables and runs terraform

set -euo pipefail

# Load environment variables
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/.env.local.tfvars"

# Export all required environment variables for Google provider
# TF_VAR_* variables are automatically picked up by Terraform as input variables
export TF_VAR_access_token="${GOOGLE_ACCESS_TOKEN}"

export GOOGLE_PROJECT="${GOOGLE_PROJECT}"
export GOOGLE_CLOUD_PROJECT="${GOOGLE_CLOUD_PROJECT}"
export GOOGLE_REGION="${GOOGLE_REGION}"

# Floci endpoint overrides for all GCP services
export GOOGLE_API_ENDPOINT_OVERRIDES_SECRETMANAGER="${GOOGLE_API_ENDPOINT_OVERRIDES_SECRETMANAGER}"
export GOOGLE_API_ENDPOINT_OVERRIDES_PUBSUB="${GOOGLE_API_ENDPOINT_OVERRIDES_PUBSUB}"
export GOOGLE_API_ENDPOINT_OVERRIDES_STORAGE="${GOOGLE_API_ENDPOINT_OVERRIDES_STORAGE}"
export GOOGLE_API_ENDPOINT_OVERRIDES_IAM="${GOOGLE_API_ENDPOINT_OVERRIDES_IAM}"
export GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDKMS="${GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDKMS}"
export GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDRESOURCEMANAGER="${GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDRESOURCEMANAGER}"
export GOOGLE_API_ENDPOINT_OVERRIDES_SERVICEUSAGE="${GOOGLE_API_ENDPOINT_OVERRIDES_SERVICEUSAGE}"
export GOOGLE_API_ENDPOINT_OVERRIDES_LOGGING="${GOOGLE_API_ENDPOINT_OVERRIDES_LOGGING}"
export GOOGLE_API_ENDPOINT_OVERRIDES_MONITORING="${GOOGLE_API_ENDPOINT_OVERRIDES_MONITORING}"
export GOOGLE_API_ENDPOINT_OVERRIDES_BIGQUERY="${GOOGLE_API_ENDPOINT_OVERRIDES_BIGQUERY}"
export GOOGLE_API_ENDPOINT_OVERRIDES_COMPUTE="${GOOGLE_API_ENDPOINT_OVERRIDES_COMPUTE}"
export GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDRUN="${GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDRUN}"
export GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDFUNCTIONS="${GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDFUNCTIONS}"
export GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDSQL="${GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDSQL}"
export GOOGLE_API_ENDPOINT_OVERRIDES_FIRESTORE="${GOOGLE_API_ENDPOINT_OVERRIDES_FIRESTORE}"
export GOOGLE_API_ENDPOINT_OVERRIDES_DATASTORE="${GOOGLE_API_ENDPOINT_OVERRIDES_DATASTORE}"
export GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDTASKS="${GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDTASKS}"
export GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDSCHEDULER="${GOOGLE_API_ENDPOINT_OVERRIDES_CLOUDSCHEDULER}"
export GOOGLE_API_ENDPOINT_OVERRIDES_EVENTARC="${GOOGLE_API_ENDPOINT_OVERRIDES_EVENTARC}"
export GOOGLE_API_ENDPOINT_OVERRIDES_IAMCREDENTIALS="${GOOGLE_API_ENDPOINT_OVERRIDES_IAMCREDENTIALS}"
export GOOGLE_API_ENDPOINT_OVERRIDES_STS="${GOOGLE_API_ENDPOINT_OVERRIDES_STS}"
export GOOGLE_API_ENDPOINT_OVERRIDES_FIREBASEAUTH="${GOOGLE_API_ENDPOINT_OVERRIDES_FIREBASEAUTH}"
export GOOGLE_API_ENDPOINT_OVERRIDES_BILLING="${GOOGLE_API_ENDPOINT_OVERRIDES_BILLING}"

# Also set emulator host variables for client libraries
export STORAGE_EMULATOR_HOST="http://localhost:4588"
export PUBSUB_EMULATOR_HOST="localhost:4588"
export FIRESTORE_EMULATOR_HOST="localhost:4588"
export DATASTORE_EMULATOR_HOST="localhost:4588"
export SECRET_MANAGER_EMULATOR_HOST="http://localhost:4588"

# Run terraform with all arguments passed through
exec terraform "$@"